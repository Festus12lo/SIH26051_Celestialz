// ARCHITECTURAL VALIDATION ENGINE
// ==========================================

export function validateApartmentPlan(): ArchitecturalValidationIssue[] {
  const issues: ArchitecturalValidationIssue[] = [];

  // Check 1: Exactly 6 residential apartments
  if (APARTMENT_UNITS.length !== 6) {
    issues.push({
      severity: 'error',
      category: 'room',
      message: `Expected exactly 6 residential units, found ${APARTMENT_UNITS.length}.`,
    });
  }

  // Check 2: Unit ID coverage
  const expectedUnitIds = ['A01', 'A02', 'B01', 'B02', 'C01', 'C02'];
  for (const id of expectedUnitIds) {
    const unit = APARTMENT_UNITS.find((u) => u.id === id);
    if (!unit) {
      issues.push({
        severity: 'error',
        category: 'room',
        message: `Missing required apartment unit ID: ${id}`,
      });
    }
  }

  // Check 3: Every window references an actual existing roomId
  const roomIds = new Set(APARTMENT_ROOMS.map((r) => r.id));
  for (const win of APARTMENT_WINDOWS) {
    if (!roomIds.has(win.roomId)) {
      issues.push({
        severity: 'error',
        category: 'window',
        message: `Orphan window detected: ${win.id} references non-existent roomId "${win.roomId}".`,
        objectId: win.id,
      });
    }
  }

  // Check 4: Every room that requires daylight has at least one allocated window or atrium aperture
  const daylightRooms = APARTMENT_ROOMS.filter(
    (r) => r.daylightPriority === 'high' && r.type !== 'atrium' && r.type !== 'roof-terrace' && r.type !== 'balcony'
  );
  for (const room of daylightRooms) {
    const hasWindow = APARTMENT_WINDOWS.some((w) => w.roomId === room.id);
    if (!hasWindow) {
      issues.push({
        severity: 'warning',
        category: 'window',
        message: `Room "${room.name}" (${room.id}) has high daylight priority but no window registered.`,
        objectId: room.id,
      });
    }
  }

  // Check 5: Doors connect real rooms
  for (const door of APARTMENT_DOORS) {
    if (!roomIds.has(door.roomId)) {
      issues.push({
        severity: 'error',
        category: 'door',
        message: `Door "${door.id}" references invalid source roomId "${door.roomId}".`,
        objectId: door.id,
      });
    }
  }

  // Verification info
  issues.push({
    severity: 'info',
    category: 'structure',
    message: `Plan verified: 6 residential units, ${APARTMENT_ROOMS.length} architectural spaces, ${APARTMENT_WINDOWS.length} scheduled windows, ${APARTMENT_DOORS.length} doors.`,
  });

  return issues;
}
