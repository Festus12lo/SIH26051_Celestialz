import * as THREE from 'three';

export type RoomType =
  | 'living'
  | 'dining'
  | 'kitchen'
  | 'bedroom'
  | 'master-bedroom'
  | 'bathroom'
  | 'powder-room'
  | 'corridor'
  | 'entry'
  | 'stair'
  | 'studio'
  | 'utility'
  | 'storage'
  | 'balcony'
  | 'atrium'
  | 'service'
  | 'roof-terrace';

export type SpaceOwnership = 'private-unit' | 'shared' | 'exterior' | 'atrium';

export interface ApartmentRoom {
  id: string;
  unitId: string; // e.g. "A01", "A02", "B01", "B02", "C01", "C02", or "shared"
  type: RoomType;
  floor: number; // 0 = Ground, 1 = First, 2 = Second, 3 = Roof
  name: string;
  bounds: THREE.Box3;
  center: THREE.Vector3;
  privacy: 'public' | 'semi-private' | 'private' | 'service';
  daylightPriority: 'high' | 'medium' | 'low';
  ventilationPriority: 'high' | 'medium' | 'low';
  exteriorExposure: 'south' | 'west' | 'east' | 'north' | 'atrium' | 'internal';
  approxArea: number; // m²
}

export interface ApartmentUnit {
  id: string;
  floor: 0 | 1 | 2;
  type: '2BR' | '2BR-STUDIO';
  name: string;
  rooms: ApartmentRoom[];
  entryPosition: THREE.Vector3;
  approximateArea: number; // m² excluding balconies & shared areas
  balconyArea?: number;
  orientation: string;
}

export interface ApartmentWindow {
  id: string;
  roomId: string;
  unitId: string;
  facade: 'north' | 'south' | 'east' | 'west' | 'atrium';
  position: THREE.Vector3;
  width: number;
  height: number;
  sillHeight: number;
  orientation: THREE.Vector3;
  glazingType: 'clear' | 'low-e' | 'frosted' | 'clerestory';
  shading: 'balcony' | 'jaali' | 'deep-reveal' | 'wing-wall' | 'none';
  ventilationRole: 'cross-flow' | 'stack-intake' | 'stack-exhaust' | 'daylight-only';
  description: string;
}

export interface ArchitecturalDoor {
  id: string;
  roomId: string;
  connectsTo: string;
  position: THREE.Vector3;
  width: number;
  height: number;
  rotationY: number;
  type: 'entry' | 'interior' | 'pocket' | 'balcony-slider';
}

export interface ArchitecturalValidationIssue {
  severity: 'warning' | 'error' | 'info';
  category: 'room' | 'window' | 'door' | 'circulation' | 'structure';
  message: string;
  objectId?: string;
}

